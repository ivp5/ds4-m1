#!/usr/bin/env python3
"""Generate the compiled, program-specific Metal profile. No model data needed."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def pack_profiles(profiles):
    first=next(iter(profiles.values()))
    common={k:v for k,v in first.items() if all(p.get(k)==v for p in profiles.values())}
    return {'common':common,'programs':{kind:{k:v for k,v in p.items() if k not in common} for kind,p in profiles.items()}}
def profiles():
    data=json.loads((ROOT/'ds4_defaults.json').read_text())
    return {kind:{**data['common'],**p} for kind,p in data['programs'].items()}
def generate():
    out=['/* Generated by gguf-tools/generate_defaults.py. */']
    for kind, vals in profiles().items():
        out.append('static const char *const llms_profile_'+kind+'[][2] = {')
        for k,v in sorted(vals.items()): out.append('    {'+json.dumps(k)+', '+json.dumps(v)+'},')
        out.append('};')
    return '\n'.join(out)+'\n'
if __name__=='__main__': (ROOT/'ds4_defaults.h').write_text(generate())
